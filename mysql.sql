-- Create Database
CREATE DATABASE IF NOT EXISTS `sotopo` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `sotopo`;

-- 1. News Table
CREATE TABLE IF NOT EXISTS `news` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `tag` VARCHAR(255) NOT NULL,
  `date` VARCHAR(255) NOT NULL,
  `title` VARCHAR(255) NOT NULL,
  `summary` TEXT NOT NULL,
  `image_url` TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. Committees Table
CREATE TABLE IF NOT EXISTS `committees` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `name` VARCHAR(255) NOT NULL,
  `role` VARCHAR(255) NOT NULL,
  `description` TEXT NOT NULL,
  `image_url` TEXT NOT NULL,
  `level` INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. Announcements Table
CREATE TABLE IF NOT EXISTS `announcements` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `announcement_number` VARCHAR(255) NOT NULL,
  `topic` VARCHAR(255) NOT NULL,
  `approve_date` VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3.1. Approved Monks Table
CREATE TABLE IF NOT EXISTS `approved_monks` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `announcement_id` INT NOT NULL,
  `monk_name` VARCHAR(255) NOT NULL,
  `temple` VARCHAR(255) NOT NULL,
  `destination` VARCHAR(255) NOT NULL,
  `approve_date` VARCHAR(255) NOT NULL,
  FOREIGN KEY (`announcement_id`) REFERENCES `announcements`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. Offices Table
CREATE TABLE IF NOT EXISTS `offices` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `name` VARCHAR(255) NOT NULL,
  `address` TEXT NOT NULL,
  `phone` VARCHAR(255) NOT NULL,
  `hours` VARCHAR(255) NOT NULL,
  `type` VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. Applications Table
CREATE TABLE IF NOT EXISTS `applications` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `tracking_number` VARCHAR(255) NOT NULL UNIQUE,
  `monk_name` VARCHAR(255) NOT NULL,
  `temple` VARCHAR(255) NOT NULL,
  `destination` VARCHAR(255) NOT NULL,
  `status` VARCHAR(255) NOT NULL,
  `step` INT NOT NULL,
  `updated_at` VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

